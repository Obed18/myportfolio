export const getImpactProjectBySlug = (
  slug: string
): ImpactProject | undefined => {
  return impactProjects.find((project) => project.slug === slug);
};

export const getRelatedImpactProjects = (
  currentSlug: string,
  limit = 3
): ImpactProject[] => {
  return impactProjects
    .filter((project) => project.slug !== currentSlug)
    .slice(0, limit);
};
